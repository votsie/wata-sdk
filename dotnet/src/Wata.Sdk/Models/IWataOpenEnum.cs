namespace Wata.Sdk.Models;

/// <summary>
/// Маркерный интерфейс для "открытых" enum'ов WATA SDK.
/// <para>
/// Сервер WATA — живой API, который может добавить новое значение перечисления
/// раньше, чем клиентские библиотеки об этом узнают. Обычный enum языка C# в этой
/// ситуации ронял бы разбор ответа. Вместо этого каждое перечисление из раздела 6
/// спецификации реализовано как <c>readonly struct</c>, которая хранит исходную
/// строку от сервера: известные значения доступны как статические поля
/// (<see cref="Currency.Rub"/> и т.п.), а неизвестное значение просто сохраняется
/// в <see cref="Value"/> и не приводит к исключению.
/// </para>
/// </summary>
public interface IWataOpenEnum
{
    /// <summary>Исходное строковое значение, как его прислал сервер.</summary>
    string Value { get; }
}
